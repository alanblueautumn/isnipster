import MacShared
import MacPreferences
// 阅读路线
// 读取按颜色 → 文件 → 图片 → URL → 文字选择最具体表示；写入时为目标应用提供合适的表示。
// AppKit 的 NSPasteboard/NSWorkspace 访问 macOS 全局剪贴板和前台应用；Foundation 提供 Data/URL/UUID 等跨平台值类型。
import AppKit
import ClipboardFeature
import Foundation
import iSnipsterCore
// 官方参考（NSPasteboard 多类型表示）：https://developer.apple.com/documentation/appkit/nspasteboard

/// NSPasteboard 的平台适配器。
///
/// macOS 剪贴板不是单值变量，而是一组带 UTI/type 的 representations。同一张图片可同时
/// 提供 PNG 和 TIFF，接收应用会选择自己认识的格式。整个对象受 MainActor 保护。
@MainActor
public final class MacPasteboardClient: PasteboardClient {
    public static let colorType = NSPasteboard.PasteboardType("com.isnipster.color")

    private let imageDecoder = ClipboardImageDecoder()
    private var imageWriteID: UUID?
    private let pasteboard: NSPasteboard
    private let transientTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    ]

    public init(pasteboard: NSPasteboard = .general) {
        // `.general` 是用户按 Cmd-C/Cmd-V 使用的全局剪贴板；注入参数使单元场景可替换为命名剪贴板。
        self.pasteboard = pasteboard
    }

    public var changeCount: Int { pasteboard.changeCount }

    /// 读取当前可用的最具体内容表示；超预算、隐私标记或解码失败时返回 nil，表示本轮不采集。
    public func readSnapshot(maxBytes: Int) async -> ClipboardSnapshot? {
        // 密码管理器等应用会标记 transient/concealed；命中任意一种就不采集，
        // 这是隐私边界，而不是普通格式兼容逻辑。
        guard transientTypes.allSatisfy({ pasteboard.availableType(from: [$0]) == nil }) else {
            return nil
        }

        // NSWorkspace 是 AppKit 对“当前工作区”的入口，可查询前台应用、监听睡眠/唤醒等系统事件。
        let sourceApplication = NSWorkspace.shared.frontmostApplication

        // 按“最具体到最通用”读取，避免图片/文件同时带有文本 representation 时被误判。
        if let color = pasteboard.string(forType: Self.colorType), color.utf8.count <= maxBytes {
            return snapshot(
                content: .color(color),
                sourceApplication: sourceApplication
            )
        }

        let fileObjects = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) ?? []
        let urls = fileObjects.compactMap { ($0 as? NSURL) as URL? }
        if !urls.isEmpty {
            let content = ClipboardContent.files(urls)
            guard content.estimatedBytes <= maxBytes else { return nil }
            return snapshot(
                content: content,
                sourceApplication: sourceApplication
            )
        }

        // NSPasteboard 读取留在 MainActor；只把 Data 和字符串快照交给后台 actor。
        // 不把 NSRunningApplication 跨隔离域传递，也不在 await 后重新读取剪贴板。
        if let rawImage = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            guard rawImage.count <= maxBytes else { return nil }
            let sourceName = sourceApplication?.localizedName
            let sourceBundle = sourceApplication?.bundleIdentifier
            guard let content = await imageDecoder.decode(rawImage, maxBytes: maxBytes),
                  !Task.isCancelled else { return nil }
            return ClipboardSnapshot(
                content: content,
                sourceApplicationName: sourceName,
                sourceBundleIdentifier: sourceBundle
            )
        }

        if let urlString = pasteboard.string(forType: .URL),
           let url = URL(string: urlString),
           urlString.utf8.count <= maxBytes {
            return snapshot(
                content: .url(url),
                sourceApplication: sourceApplication
            )
        }

        if let text = pasteboard.string(forType: .string), text.utf8.count <= maxBytes {
            if let url = ClipboardContent.detectedWebURL(in: text) {
                return snapshot(
                    content: .url(url),
                    sourceApplication: sourceApplication
                )
            }
            return snapshot(
                content: .text(text),
                sourceApplication: sourceApplication
            )
        }

        return nil
    }

    /// 同步写入已准备好的数据；清空旧剪贴板后若写失败会抛错，不能假定自动恢复旧内容。
    public func write(_ content: ClipboardContent) throws {
        imageWriteID = nil
        // clearContents 清除旧内容并改变 changeCount，再写入本次内容的多种表示。
        // 这不是数据库事务：后面的写入若失败，旧内容不会自动恢复。
        pasteboard.clearContents()

        let succeeded: Bool
        switch content {
        case let .text(value):
            succeeded = pasteboard.setString(value, forType: .string)
        case let .url(url):
            // URL 对象通常只提供 public.url；不少文本输入框只接受 public.utf8-plain-text。
            // 同一个 pasteboard item 同时提供两种表示，目标应用可自行选择最合适的类型。
            // NSPasteboardItem 是“一条剪贴板记录”，可携带多个 type；不是一个 UI 列表项。
            let item = NSPasteboardItem()
            let value = url.absoluteString
            item.setString(value, forType: .URL)
            item.setString(value, forType: .string)
            succeeded = pasteboard.writeObjects([item])
        case let .files(urls):
            succeeded = pasteboard.writeObjects(urls.map { $0 as NSURL })
        case let .color(value):
            let item = NSPasteboardItem()
            item.setString(value, forType: .string)
            item.setString(value, forType: Self.colorType)
            succeeded = pasteboard.writeObjects([item])
        case let .imagePNG(data, _, _):
            // 同步入口只发布已有 PNG；完整图片复制由 writeImage 在后台准备 TIFF。
            // Finder 目录粘贴仍由展示层改写为文件承诺。
            let item = NSPasteboardItem()
            item.setData(data, forType: .png)
            succeeded = pasteboard.writeObjects([item])
        }

        guard succeeded else {
            throw AppFailure.operationFailed(AppText.text("写入系统剪贴板失败"))
        }
    }

    /// 后台准备 TIFF 后验证操作 ID 和系统 changeCount，再一次发布 PNG/TIFF 多表示。
    public func writeImage(_ content: ClipboardContent) async throws {
        try Task.checkCancellation()
        guard case let .imagePNG(data, _, _) = content else {
            try write(content)
            return
        }
        let id = UUID()
        imageWriteID = id
        let previousChangeCount = pasteboard.changeCount
        defer { if imageWriteID == id { imageWriteID = nil } }
        // 保留原 PNG/TIFF 双表示；编码失败仍可用 PNG，取消则绝不写回。
        let tiff = try? await imageDecoder.tiffData(fromPNG: data)
        try Task.checkCancellation()
        guard imageWriteID == id, pasteboard.changeCount == previousChangeCount else {
            throw CancellationError()
        }
        let item = NSPasteboardItem()
        item.setData(data, forType: .png)
        if let tiff { item.setData(tiff, forType: .tiff) }
        pasteboard.clearContents()
        guard pasteboard.writeObjects([item]) else {
            throw AppFailure.operationFailed(AppText.text("写入系统剪贴板失败"))
        }
    }

    public func writePNG(_ data: Data) async throws {
        try await writeImage(.imagePNG(data, pixelWidth: 0, pixelHeight: 0))
    }

    /// 把系统应用对象转换为名称和 bundle ID；业务层只携带值，不跨并发域持有 NSRunningApplication。
    private func snapshot(
        content: ClipboardContent,
        sourceApplication: NSRunningApplication?
    ) -> ClipboardSnapshot {
        ClipboardSnapshot(
            content: content,
            sourceApplicationName: sourceApplication?.localizedName,
            sourceBundleIdentifier: sourceApplication?.bundleIdentifier
        )
    }
}
